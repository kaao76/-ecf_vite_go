<section class="page-cgv">
    <h1>Conditions générales de vente</h1>

    <h2>1. Commandes</h2>
    <p>
    Pour passer commande, le client doit disposer d'un compte
    utilisateur et être connecté au site Vite & Gourmand.

    Le client sélectionne un menu, indique la date de sa prestation,
    l'heure et l'adresse de livraison, ainsi que le nombre de personnes.

    Chaque menu possède un nombre minimum de personnes à respecter.

    Avant de confirmer sa commande, le client peut consulter
    le récapitulatif des informations et le montant total.
</p>

    <h2>2. Tarifs et réductions</h2>
    <p>
    Le prix de chaque menu est indiqué sur le site Vite & Gourmand.
    Il est calculé en fonction du nombre de personnes
    sélectionné lors de la commande.
</p>

<p>
    Chaque menu impose un nombre minimum de personnes.
    Le client doit respecter ce minimum pour pouvoir
    valider sa commande.
</p>

<p>
    Une réduction de 10 % sur le prix du menu est appliquée
    lorsque le nombre de personnes commandées dépasse
    d'au moins 5 personnes le minimum indiqué pour ce menu.
</p>

<p>
    Le montant de la commande, comprenant le prix du menu
    et les éventuels frais de livraison, est présenté
    au client avant la validation.
</p>

    <h2>3. Livraison</h2>
    <p>
    Vite & Gourmand propose un service de livraison
    pour les commandes de menus.
</p>

<p>
    La livraison est gratuite dans la ville de Bordeaux.
</p>

<p>
    Pour toute livraison en dehors de Bordeaux,
    les frais de livraison comprennent un montant fixe
    de 5 €, auquel s'ajoute un coût de 0,59 €
    par kilomètre parcouru.
</p>

<p>
    Lors de sa commande, le client doit indiquer
    l'adresse de livraison, la date de la prestation
    et l'heure de livraison souhaitée.
</p>

<p>
    Les frais de livraison sont indiqués dans
    le récapitulatif de la commande avant sa validation.
</p>

    <h2>4. Modification et annulation</h2>

    <p>
    Le client peut consulter ses commandes
    depuis son espace personnel sur le site
    Vite & Gourmand.
</p>

<p>
    Une commande peut être modifiée ou annulée
    par le client tant qu'elle n'a pas encore
    été acceptée par le traiteur.
</p>

<p>
    Une fois la commande acceptée,
    le client ne peut plus la modifier
    ou l'annuler directement depuis
    son espace personnel.
</p>

    <h2>5. Prêt et restitution du matériel</h2>

    <p>
    Dans le cadre de certaines prestations,
    Vite & Gourmand peut mettre du matériel
    à la disposition du client.
</p>

<p>
    Le matériel prêté doit être restitué
    dans un délai de 10 jours ouvrés,
    conformément aux conditions prévues
    pour la prestation.
</p>

<p>
    En cas de non-restitution du matériel,
    une pénalité de 600 € est prévue
    dans les conditions du prêt.
</p>
